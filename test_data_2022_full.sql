DELIMITER $$

CREATE PROCEDURE generate_2022_reports()
BEGIN
    DECLARE done INT DEFAULT FALSE;
    DECLARE ent_id VARCHAR(50);
    DECLARE ent_nature INT;
    DECLARE ent_industry INT;
    DECLARE ent_region INT;
    DECLARE period INT;
    DECLARE base_count INT;
    DECLARE variation INT;
    DECLARE report_id_str VARCHAR(50);
    
    -- 游标：遍历所有企业
    DECLARE enterprise_cursor CURSOR FOR 
        SELECT enterprise_id, nature, industry, region FROM enterprise_info WHERE status = 3;
    
    DECLARE CONTINUE HANDLER FOR NOT FOUND SET done = TRUE;
    
    OPEN enterprise_cursor;
    
    read_loop: LOOP
        FETCH enterprise_cursor INTO ent_id, ent_nature, ent_industry, ent_region;
        IF done THEN
            LEAVE read_loop;
        END IF;
        
        -- 为每个企业生成2022年12个月的数据
        SET period = 1;
        SET base_count = 100 + FLOOR(RAND() * 200); -- 基础人数 100-300
        
        WHILE period <= 12 DO
            -- 计算当月人数变化 (-20 到 +30)
            SET variation = FLOOR(RAND() * 51) - 20;
            SET base_count = base_count + variation;
            IF base_count < 50 THEN
                SET base_count = 50; -- 最少50人
            END IF;
            
            -- 生成 report_id
            SET report_id_str = CONCAT('RPT_', SUBSTRING(ent_id, 5), '_2022', LPAD(period, 2, '0'));
            
            -- 插入 report_info
            INSERT INTO report_info (report_id, construction_count, investigation_count, reduction_type, reason1, reason1_desc, reason2, reason2_desc, reason3, reason3_desc, other_reason)
            VALUES (
                report_id_str,
                base_count - variation,
                base_count,
                IF(variation < 0, 2, 1),
                IF(variation < 0, 201 + FLOOR(RAND() * 3), 101 + FLOOR(RAND() * 3)),
                IF(variation < 0, '人员减少原因说明', '人员增加原因说明'),
                NULL, NULL, NULL, NULL, NULL
            );
            
            -- 插入 enterprise_report_info (状态3=审核通过, 4=已归档)
            INSERT INTO enterprise_report_info (
                enterprise_id, period_id, report_id, old_report_id, reason_return, 
                status, period_start_time, period_end_time, created_at, updated_at,
                enterprise_nature, enterprise_industry, enterprise_region
            )
            SELECT 
                ent_id,
                period_id,
                report_id_str,
                NULL,
                NULL,
                IF(period <= 10, 4, 3), -- 前10个月归档，后2个月审核通过
                period_start_time,
                period_end_time,
                DATE_ADD(period_start_time, INTERVAL 2 DAY),
                DATE_ADD(period_start_time, INTERVAL 8 DAY),
                ent_nature,
                ent_industry,
                ent_region
            FROM period_info 
            WHERE investigate_time = CONCAT('2022-', LPAD(period, 2, '0'));
            
            -- 插入审核记录
            INSERT INTO report_audit_history (enterprise_id, period_id, report_id, audit_level, auditor, audit_result, audit_opinion, audit_time)
            SELECT 
                ent_id,
                pi.period_id,
                report_id_str,
                1,
                CASE 
                    WHEN ent_region DIV 100 = 5301 THEN 'admin_kunming'
                    WHEN ent_region DIV 100 = 5303 THEN 'admin_qujing'
                    WHEN ent_region DIV 100 = 5329 THEN 'admin_dali'
                    WHEN ent_region DIV 100 = 5325 THEN 'admin_honghe'
                    WHEN ent_region DIV 100 = 5307 THEN 'admin_lijiang'
                    WHEN ent_region DIV 100 = 5328 THEN 'admin_xishuangbanna'
                    WHEN ent_region DIV 100 = 5305 THEN 'admin_baoshan'
                    WHEN ent_region DIV 100 = 5306 THEN 'admin_zhaotong'
                    ELSE 'admin_kunming'
                END,
                1,
                '市级审核通过',
                DATE_ADD(pi.period_start_time, INTERVAL 5 DAY)
            FROM period_info pi
            WHERE pi.investigate_time = CONCAT('2022-', LPAD(period, 2, '0'));
            
            INSERT INTO report_audit_history (enterprise_id, period_id, report_id, audit_level, auditor, audit_result, audit_opinion, audit_time)
            SELECT 
                ent_id,
                pi.period_id,
                report_id_str,
                2,
                'admin_province',
                1,
                '省级审核通过',
                DATE_ADD(pi.period_start_time, INTERVAL 8 DAY)
            FROM period_info pi
            WHERE pi.investigate_time = CONCAT('2022-', LPAD(period, 2, '0'));
            
            SET period = period + 1;
        END WHILE;
        
    END LOOP;
    
    CLOSE enterprise_cursor;
END$$

DELIMITER ;

-- 执行存储过程生成数据
CALL generate_2022_reports();

-- 删除存储过程
DROP PROCEDURE IF EXISTS generate_2022_reports;

